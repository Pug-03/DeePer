export function translate(lang, key, vars) {
  const table = STRINGS[lang] || STRINGS.th;
  let s = table[key];
  if (s == null) s = STRINGS.th[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.replaceAll(`{${k}}`, String(vars[k]));
    }
  }
  return s;
}
